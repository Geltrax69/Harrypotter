// Original centerline vector alphabet.
//
// Every glyph is authored as one or more centerline strokes in a normalized em
// box. Coordinate convention (glyph-local):
//   x: 0 = left edge of the glyph, advances rightward.
//   y: 0 = baseline, negative = up toward cap/ascender, positive = descender.
// A lowercase x-height is ~0.5, cap/ascender height ~0.72, descender ~0.2.
//
// These are hand-authored polylines that trace the SHAPE of each letter (not
// generic squiggles): e.g. 'A' is two diagonals plus a crossbar, 'o' is a
// closed loop, '5' is a top bar + stem + bowl. The glyphs are deliberately
// simple single-weight centerlines so they read as handwriting when stroked
// with a rounded pen. No external or licensed font is used; this table is the
// sole source of letterform geometry.
public enum BaseAlphabet {

    /// The visible fallback glyph used for any unsupported character.
    public static let fallbackKey = "?"

    /// All base single-character glyphs, keyed by their character.
    public static let glyphs: [String: [InkStroke]] = build()

    /// The set of characters the base alphabet can render (excludes space,
    /// which is handled as advance-only during layout).
    public static var supportedCharacters: Set<Character> {
        Set(glyphs.keys.compactMap { $0.first })
    }

    /// Nominal advance width for each glyph in em units. Falls back to a default.
    public static func advance(for key: String) -> Double {
        advances[key] ?? 0.62
    }

    private static let advances: [String: Double] = defaultAdvances()

    // MARK: - Lookup

    /// Whether the alphabet has an authored glyph for a character (case-folding
    /// salvage included). Excludes the implicit '?' fallback.
    public static func hasGlyph(for character: Character) -> Bool {
        let key = String(character)
        if glyphs[key] != nil { return true }
        let swapped = key.uppercased() == key ? key.lowercased() : key.uppercased()
        return glyphs[swapped] != nil
    }

    /// Returns the base strokes for a character, or the `?` fallback strokes.
    public static func strokes(for character: Character) -> (strokes: [InkStroke], isFallback: Bool) {
        let key = String(character)
        if let s = glyphs[key] { return (s, false) }
        // Case-insensitive salvage: an uppercase-only author entry can serve
        // lowercase and vice versa before resorting to the visible '?'.
        let swapped = key.uppercased() == key ? key.lowercased() : key.uppercased()
        if let s = glyphs[swapped] { return (s, false) }
        return (glyphs[fallbackKey] ?? [], true)
    }

